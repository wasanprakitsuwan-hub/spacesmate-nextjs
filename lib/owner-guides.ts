/**
 * Owner guides (คู่มือเจ้าของ): long-form Thai how-to pages at /guide/<slug>.
 *
 * WHY THESE EXIST
 *   Google's AI Overview for owner queries such as "การปล่อยเช่าอพาร์ทเม้นท์"
 *   is built from three blocks: where to list, contract and law, and how-to
 *   steps. It cites pages that answer one topic in depth, with a short answer up
 *   top and an FAQ. SpacesMate had no such page, so it could not be cited.
 *   Plan: https://claude.ai/artifact/3VZpBogyhc9bdehYDFSRy9 (27 Nov 2026).
 *
 * THE FORMAT (every guide)
 *   - `summary`: a 2 to 3 sentence answer, the text answer engines lift.
 *   - `keyFacts`: up to three numbers with a one-line meaning.
 *   - `sections`: headings written as the question an owner types; each opens
 *     with `answer` (40 to 60 words), then items an owner can act on.
 *   - `faq`: rendered on the page and as FAQPage JSON-LD (Google needs both).
 *   - `sources`: every legal number links to the official text.
 *
 * THAI ONLY
 *   These target Thai queries and have no English twin, like /building. They
 *   are not in lib/routes-i18n, so links to them stay Thai on /en pages. Keep
 *   this module out of any /en page's import graph (scripts/check-en-coverage).
 *
 * LEGAL FACTS
 *   Checked on 27 Nov 2026 against ประกาศคณะกรรมการว่าด้วยสัญญา เรื่อง ให้ธุรกิจ
 *   การให้เช่าอาคารเพื่ออยู่อาศัยเป็นธุรกิจที่ควบคุมสัญญา พ.ศ. 2568
 *   (ratchakitcha.soc.go.th/documents/72766.pdf): scope 3+ units, deposit plus
 *   advance rent max 3 months, utilities at no more than the provider's rate,
 *   deposit back in 7 days (14 after deducting damage), condition record
 *   attached to the lease, tenant early exit after half the term with 30 days'
 *   written notice, owner termination after a 30-day written demand.
 *   Re-check before changing any of these lines.
 */

