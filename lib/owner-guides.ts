/** Published guides, in hub order. A guide joins the hub and sitemap by being listed here. */
export const OWNER_GUIDES: OwnerGuide[] = [PILLAR]

export function findOwnerGuide(rawSlug: string): OwnerGuide | null {
  let slug = rawSlug
  try { slug = decodeURIComponent(rawSlug) } catch { /* keep raw */ }
  return OWNER_GUIDES.find(g => g.slug === slug) ?? null
}

export function ownerGuidePath(g: OwnerGuide): string {
  return `/guide/${g.slug}`
}

